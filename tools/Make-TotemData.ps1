param(
  [Parameter(Mandatory=$true)][string]$Dbc,
  [string]$Out = ""
)
# pfUI Octo :: writes modules\octototems-data.lua (OctoTotems) from the client's spell data.
#   1. powershell -File ..\OctoBG\tools\MpqRead.ps1 -OutDir <dir> -Names "DBFilesClient\Spell.dbc","DBFilesClient\SpellIcon.dbc","DBFilesClient\SpellDuration.dbc"
#   2. powershell -ExecutionPolicy Bypass -File tools\Make-TotemData.ps1 -Dbc <dir>
# Reads <dir>\patch-O\DBFilesClient_Spell.dbc + _SpellIcon.dbc (the server's files) and
# <dir>\patch-4\DBFilesClient_SpellDuration.dbc. Spell.dbc 1.12 columns: 0 id, 30 duration index,
# 61-63 effects (87-90 = SUMMON_TOTEM_SLOT1-4: fire, earth, water, air), 117 icon, 120 name, 129 rank, 160 family (11 shaman).

$src = @"
using System; using System.IO; using System.Text; using System.Collections.Generic;
public class TotemDbc {
  byte[] b; int n, rs, sb;
  public TotemDbc(string p) { b = File.ReadAllBytes(p); n = BitConverter.ToInt32(b, 4); rs = BitConverter.ToInt32(b, 12); sb = 20 + n * rs; }
  public int Count { get { return n; } }
  public int I(int r, int k) { return BitConverter.ToInt32(b, 20 + r * rs + k * 4); }
  public string S(int o) { int e = sb + o; while (b[e] != 0) e++; return Encoding.UTF8.GetString(b, sb + o, e - sb - o); }
  static string Esc(string s) { return s.Replace("\\", "\\\\").Replace("\"", "\\\""); }
  public static string Make(string spell, string icon, string dur) {
    var sp = new TotemDbc(spell); var ic = new TotemDbc(icon); var du = new TotemDbc(dur);
    var icons = new Dictionary<int, string>(); for (int i = 0; i < ic.Count; i++) icons[ic.I(i, 0)] = ic.S(ic.I(i, 1));
    var durs = new Dictionary<int, int>(); for (int i = 0; i < du.Count; i++) durs[du.I(i, 0)] = du.I(i, 1);
    var order = new List<string>(); var el = new Dictionary<string, int>(); var ico = new Dictionary<string, string>();
    var ranks = new Dictionary<string, StringBuilder>(); var ids = new Dictionary<string, StringBuilder>();
    for (int i = 0; i < sp.Count; i++) {
      if (sp.I(i, 160) != 11) continue;
      int slot = 0;
      for (int e = 0; e < 3; e++) { int ef = sp.I(i, 61 + e); if (ef >= 87 && ef <= 90) { slot = ef - 86; break; } }
      if (slot == 0) continue;
      string name = sp.S(sp.I(i, 120)), rank = sp.S(sp.I(i, 129));
      if (name.Contains("Deprecated") || name.Contains("TEST") || name.Contains("Testing") || name.Contains("Corrupt")) continue;
      int d; durs.TryGetValue(sp.I(i, 30), out d);
      if (d <= 0) continue;
      if (name == "Mana Spring Totem" && rank == "") continue; // 24 s item version
      if (!el.ContainsKey(name)) {
        order.Add(name); el[name] = slot; string t; icons.TryGetValue(sp.I(i, 117), out t); ico[name] = t ?? "";
        ranks[name] = new StringBuilder(); ids[name] = new StringBuilder();
      }
      ranks[name].Append("[\"" + Esc(rank) + "\"] = " + (d / 1000) + ", ");
      ids[name].Append(sp.I(i, 0) + ", ");
    }
    var o = new StringBuilder();
    o.Append("-- pfUI Octo :: OctoTotems data, GENERATED by tools\\Make-TotemData.ps1 from the client's Spell.dbc (patch-O),\n");
    o.Append("-- SpellIcon.dbc and SpellDuration.dbc: shaman spells with a SUMMON_TOTEM_SLOT effect. el 1 fire, 2 earth,\n");
    o.Append("-- 3 water, 4 air; dur[rank] in seconds (\"\" = a spell without ranks). Do not edit by hand.\n");
    o.Append("pfUI.totemData = {\n");
    foreach (var name in order)
      o.Append("  [\"" + Esc(name) + "\"] = { el = " + el[name] + ", icon = \"" + Esc(ico[name]) + "\", dur = { " + ranks[name] + "}, ids = { " + ids[name] + "} },\n");
    o.Append("}\n");
    return o.ToString();
  }
}
"@
if (-not $Out) { $Out = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) "..\modules\octototems-data.lua" }
Add-Type -TypeDefinition $src
$lua = [TotemDbc]::Make((Join-Path $Dbc "patch-O\DBFilesClient_Spell.dbc"), (Join-Path $Dbc "patch-O\DBFilesClient_SpellIcon.dbc"), (Join-Path $Dbc "patch-4\DBFilesClient_SpellDuration.dbc"))
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $Out)).Path + "\" + (Split-Path $Out -Leaf), $lua, (New-Object System.Text.UTF8Encoding $false))
"wrote $Out"
