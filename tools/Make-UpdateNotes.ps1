# Writes modules\updatenotes.lua (pfUI.octoNotes) from README.md's "New in x.y.z" sections.
# Run before every release, after the README section is written:
#   powershell -ExecutionPolicy Bypass -File tools\Make-UpdateNotes.ps1
# The game font has no emoji: everything outside plain ASCII is dropped, and so are ** and backticks.
param([int]$Keep = 40)
$root = Split-Path -Parent $PSScriptRoot
$lines = [IO.File]::ReadAllLines((Join-Path $root "README.md"), [Text.Encoding]::UTF8)

function Clean([string]$s) {
  $s = $s -replace '[–—]', '-' -replace '[‘’]', "'" -replace '[“”]', '"' -replace '…', '...'
  $s = $s -replace '[^\x20-\x7E]', '' -replace '\*\*', '' -replace '`', ''
  $s = $s -replace '\s+', ' '
  return $s.Trim()
}
function Lua([string]$s) { return '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }

$versions = @()
$cur = $null
foreach ($l in $lines) {
  if ($l -match '^## .*New in (\d+\.\d+\.\d+)') {
    $cur = @{ v = $Matches[1]; items = New-Object System.Collections.ArrayList }
    $versions += $cur
    continue
  }
  if ($l -match '^## ') { $cur = $null; continue }
  if ($cur -and $l -match '^- (.*)$') {
    $body = $Matches[1]
    $title = ''
    $text = ''
    if ($body -match '\*\*(.+?)\*\*(.*)$') {
      $title = Clean $Matches[1]
      $text = Clean $Matches[2]
    } else {
      $text = Clean $body
    }
    $title = $title.TrimEnd(':', '.').Trim()
    $text = $text.TrimStart(':').Trim()
    if ($title -eq '') { $title = $text; if ($title.Length -gt 70) { $title = $title.Substring(0, 67) + '...' } }
    [void]$cur.items.Add(@($title, $text))
  }
}

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('-- GENERATED by tools\Make-UpdateNotes.ps1 from README.md - do not edit by hand.')
[void]$out.AppendLine('-- What each pfUI Octo version brought: { version, { { title, text }, ... } }, newest first.')
[void]$out.AppendLine('-- updatenotify.lua shows them in the update window and sends the titles to older versions.')
[void]$out.AppendLine('pfUI.octoNotes = {')
$n = 0
foreach ($e in $versions) {
  if ($n -ge $Keep) { break }
  $n++
  [void]$out.AppendLine('  { ' + (Lua $e.v) + ', {')
  foreach ($it in $e.items) {
    [void]$out.AppendLine('    { ' + (Lua $it[0]) + ', ' + (Lua $it[1]) + ' },')
  }
  [void]$out.AppendLine('  } },')
}
[void]$out.AppendLine('}')
$path = Join-Path $root "modules\updatenotes.lua"
[IO.File]::WriteAllText($path, $out.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n"), (New-Object Text.UTF8Encoding $false))
Write-Output ("wrote " + $n + " versions to " + $path)
