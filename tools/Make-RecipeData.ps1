param(
  [Parameter(Mandatory=$true)][string]$Dbc,
  [string]$Out = ""
)
# pfUI Octo :: writes modules\professions-data.lua (every recipe of every profession, for the profession windows'
# "Missing" list; 25 Nov 2026, Javelin on Discord) from the client's own tables.
#   1. powershell -File ..\OctoBG\tools\MpqRead.ps1 -OutDir <dir> -Names "DBFilesClient\SkillLineAbility.dbc","DBFilesClient\SkillLine.dbc","DBFilesClient\Spell.dbc","DBFilesClient\SpellIcon.dbc"
#   2. powershell -ExecutionPolicy Bypass -File tools\Make-RecipeData.ps1 -Dbc <dir>
# Reads <dir>\patch-5\ SkillLine / SkillLineAbility and <dir>\patch-O\ Spell / SpellIcon (the server's newest).
# SkillLine 1.12: 0 id, 1 category (11 profession, 9 secondary), 3 name. SkillLineAbility: 0 id, 1 skill line, 2 spell,
# 7 skill needed (1 = taught by a recipe item: unknown here), 10 grey at, 11 yellow at. Spell: 0 id, 117 icon, 120 name.
# A recipe = a row with a "grey at" (10) above 0 (the profession's own rank spells have none).

$src = @"
using System; using System.IO; using System.Text; using System.Collections.Generic;
public class RecDbc {
  byte[] b; int n, rs, sb;
  public RecDbc(string p) { b = File.ReadAllBytes(p); n = BitConverter.ToInt32(b, 4); rs = BitConverter.ToInt32(b, 12); sb = 20 + n * rs; }
  public int Count { get { return n; } }
  public int I(int r, int k) { return BitConverter.ToInt32(b, 20 + r * rs + k * 4); }
  public string S(int o) { int e = sb + o; while (b[e] != 0) e++; return Encoding.UTF8.GetString(b, sb + o, e - sb - o); }
  static string Esc(string s) { return s.Replace("\\", "\\\\").Replace("\"", "\\\""); }
  static bool Junk(string n) {
    return n == "" || n.Contains("Deprecated") || n.Contains("TEST") || n.Contains("Test ") || n.Contains("QA") || n.StartsWith("OLD")
      || n.StartsWith("zz") || n.Contains("[PH]") || n.Contains("UNUSED") || n.Contains("Unused") || n.Contains("DND") || n.Contains("^");
  }
  public static string Make(string sl, string sla, string spell, string icon) {
    var lines = new RecDbc(sl); var ab = new RecDbc(sla); var sp = new RecDbc(spell); var ic = new RecDbc(icon);
    var prof = new Dictionary<int, string>();
    for (int i = 0; i < lines.Count; i++) { int c = lines.I(i, 1); if (c == 11 || c == 9) prof[lines.I(i, 0)] = lines.S(lines.I(i, 3)); }
    var icons = new Dictionary<int, string>();
    for (int i = 0; i < ic.Count; i++) { string p = ic.S(ic.I(i, 1)); int k = p.LastIndexOf('\\'); string nm = k >= 0 ? p.Substring(k + 1) : p; icons[ic.I(i, 0)] = (nm == "Temp" || nm == "temp") ? "" : nm; }
    var sname = new Dictionary<int, string>(); var sicon = new Dictionary<int, int>();
    for (int i = 0; i < sp.Count; i++) { sname[sp.I(i, 0)] = sp.S(sp.I(i, 120)); sicon[sp.I(i, 0)] = sp.I(i, 117); }
    var per = new SortedDictionary<string, SortedDictionary<string, int[]>>();
    var ico = new Dictionary<string, string>();
    for (int i = 0; i < ab.Count; i++) {
      string pn; if (!prof.TryGetValue(ab.I(i, 1), out pn)) continue;
      int grey = ab.I(i, 10), yellow = ab.I(i, 11), need = ab.I(i, 7), id = ab.I(i, 2);
      if (grey <= 0) continue;
      string name; if (!sname.TryGetValue(id, out name) || Junk(name)) continue;
      if (!per.ContainsKey(pn)) per[pn] = new SortedDictionary<string, int[]>(StringComparer.Ordinal);
      var t = per[pn]; int[] have;
      if (t.TryGetValue(name, out have) && have[1] <= yellow) continue;   // (the same name twice: the easier one)
      t[name] = new int[] { need > 1 ? need : 0, yellow, id };
      string ip; icons.TryGetValue(sicon[id], out ip); ico[pn + "|" + name] = ip ?? "";
    }
    var o = new StringBuilder();
    o.Append("-- pfUI Octo :: every recipe of every profession, GENERATED by tools\\Make-RecipeData.ps1 from the client's\n");
    o.Append("-- SkillLine / SkillLineAbility (patch-5) and Spell / SpellIcon (patch-O). Do not edit by hand.\n");
    o.Append("-- One string per profession (English name, as GetTradeSkillLine / GetCraftDisplaySkillLine give it), read only when a\n");
    o.Append("-- profession window opens: \"name^skill needed (0 = taught by a recipe: not in the client's tables)^yellow at^spell id^icon\"\n");
    o.Append("-- entries joined by \"\\n\".\n");
    o.Append("pfUI.recipeData = {\n");
    int total = 0;
    foreach (var kv in per) {
      if (kv.Value.Count < 3) continue;   // (racials and riding: nothing to craft)
      var sb2 = new StringBuilder();
      foreach (var r in kv.Value) {
        sb2.Append(r.Key + "^" + r.Value[0] + "^" + r.Value[1] + "^" + r.Value[2] + "^" + ico[kv.Key + "|" + r.Key] + "\n");
        total++;
      }
      o.Append("  [\"" + Esc(kv.Key) + "\"] = [[\n" + sb2.ToString() + "]],\n");
    }
    o.Append("}\n");
    o.Append("-- " + total + " recipes\n");
    return o.ToString();
  }
}
"@
if (-not $Out) { $Out = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) "..\modules\professions-data.lua" }
Add-Type -TypeDefinition $src
$lua = [RecDbc]::Make((Join-Path $Dbc "patch-5\DBFilesClient_SkillLine.dbc"), (Join-Path $Dbc "patch-5\DBFilesClient_SkillLineAbility.dbc"),
  (Join-Path $Dbc "patch-O\DBFilesClient_Spell.dbc"), (Join-Path $Dbc "patch-O\DBFilesClient_SpellIcon.dbc"))
if ($lua -match "]][^,]") { throw "a recipe name holds ]] and would end its Lua string" }
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $Out)).Path + "\" + (Split-Path $Out -Leaf), $lua, (New-Object System.Text.UTF8Encoding $false))
"wrote $Out"
