# pfUI Octo :: makes modules\dots-data.lua (the DoT Tracker's spell lists) from
# Cursive-Raid's spell tables (MIT, Kirchlive / Teto, after Shagu's Cursive).
# Run again when Cursive-Raid's spells change:
#   powershell -ExecutionPolicy Bypass -File tools\Make-DotsData.ps1 [-Cursive <folder>]
param([string]$Cursive = (Join-Path $PSScriptRoot "..\..\Cursive-Raid"))
$ErrorActionPreference = "Stop"
$spells = Join-Path $Cursive "spells"
if (-not (Test-Path $spells)) { throw "Cursive-Raid not found at $Cursive" }

# English names: the enUS block of Localization.lua ("key" = true)
$names = @{}
$inEn = $false
foreach ($line in Get-Content (Join-Path $Cursive "Localization.lua")) {
  if ($line -match 'RegisterTranslations\("enUS"') { $inEn = $true; continue }
  if ($inEn -and $line -match 'RegisterTranslations\(') { break }
  if ($inEn -and $line -match '^\s*\["([^"]+)"\]\s*=\s*true') { $names[$Matches[1]] = $true }
}
$small = @("of", "the", "and", "a", "an", "to", "in", "on")
function Title([string]$s) {
  $words = $s -split ' '
  $out = @()
  for ($i = 0; $i -lt $words.Count; $i++) {
    $w = $words[$i]
    if ($i -gt 0 -and $small -contains $w) { $out += $w; continue }
    if ($w.Length -gt 0) { $w = $w.Substring(0, 1).ToUpper() + $w.Substring(1) }
    # "Polymorph: cow" -> "Polymorph: Cow", "hunter's" stays
    $out += $w
  }
  return ($out -join ' ')
}
function Q([string]$s) { return '"' + ($s -replace '\\', '\\\\' -replace '"', '\"') + '"' }

$spellRx = '^\s*\[(\d+)\]\s*=\s*\{\s*name\s*=\s*L\["([^"]+)"\][^}]*?duration\s*=\s*([\d\.]+)'

# shared (raid) debuffs
$raid = New-Object System.Collections.ArrayList
$cur = $null
foreach ($line in Get-Content (Join-Path $spells "shared_debuffs.lua")) {
  if ($line -match '^\t\t([a-z_]+) = \{\s*$') {
    $cur = [ordered]@{ key = $Matches[1]; cat = ""; class = ""; raid = $false; stacks = 0; ids = New-Object System.Collections.ArrayList; name = ""; dur = 0 }
    [void]$raid.Add($cur)
    continue
  }
  if (-not $cur) { continue }
  if ($line -match '^\s*category\s*=\s*"([^"]+)"') { $cur.cat = $Matches[1] }
  elseif ($line -match '^\s*class\s*=\s*"([^"]+)"') { $cur.class = $Matches[1].ToUpper() }
  elseif ($line -match '^\s*raidRelevant\s*=\s*true') { $cur.raid = $true }
  elseif ($line -match '^\s*stacks\s*=\s*(\d+)') { $cur.stacks = [int]$Matches[1] }
  elseif ($line -match $spellRx) {
    [void]$cur.ids.Add([int]$Matches[1])
    if (-not $cur.name) { $cur.name = Title $Matches[2] }
    $d = [double]$Matches[3]
    if ($d -gt $cur.dur) { $cur.dur = $d }
  }
}

# every class's own debuffs: id -> name, duration, class
$own = New-Object System.Collections.ArrayList
foreach ($f in Get-ChildItem $spells -Filter *.lua) {
  if ($f.Name -eq "shared_debuffs.lua") { continue }
  $class = $f.BaseName.ToUpper()
  foreach ($line in Get-Content $f.FullName) {
    if ($line -match $spellRx) {
      [void]$own.Add(@([int]$Matches[1], (Title $Matches[2]), [double]$Matches[3], $class))
    }
  }
}
# shared ones go in the same id table (fallback timers for anyone's cast)
foreach ($r in $raid) { foreach ($id in $r.ids) { [void]$own.Add(@($id, $r.name, $r.dur, $r.class)) } }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("-- pfUI Octo :: DoT Tracker spell lists. GENERATED by tools\Make-DotsData.ps1 - do not edit by hand.")
[void]$sb.AppendLine("-- From Cursive-Raid's spells\*.lua (MIT licence, Kirchlive / Teto, after Shagu's Cursive).")
[void]$sb.AppendLine("--   raid  = shared debuffs worth watching on a mob: key, name, class (ITEM = weapon procs), cat")
[void]$sb.AppendLine("--           (armor, spellvuln, weaponproc, tank, healing, cc, utility, personal), raid (on at")
[void]$sb.AppendLine("--           first), stacks (most), dur (seconds), ids (every rank / form)")
[void]$sb.AppendLine("--   spells = spell id -> { name, duration, class }: timers for when ClassicAPI has none")
[void]$sb.AppendLine("pfUI.dotsData = { raid = {")
foreach ($r in $raid) {
  if ($r.ids.Count -eq 0) { continue }
  $line = "  { key = " + (Q $r.key) + ", name = " + (Q $r.name) + ", class = " + (Q $r.class) + ", cat = " + (Q $r.cat) +
    ", raid = " + ($(if ($r.raid) { "true" } else { "false" })) + ", stacks = " + $r.stacks + ", dur = " + $r.dur +
    ", ids = { " + (($r.ids | ForEach-Object { $_ }) -join ", ") + " } },"
  [void]$sb.AppendLine($line)
}
[void]$sb.AppendLine("}, spells = {")
$seen = @{}
foreach ($o in ($own | Sort-Object { $_[0] })) {
  if ($seen[$o[0]]) { continue }
  $seen[$o[0]] = $true
  [void]$sb.AppendLine("  [" + $o[0] + "] = { " + (Q $o[1]) + ", " + $o[2] + ", " + (Q $o[3]) + " },")
}
[void]$sb.AppendLine("} }")
$out = Join-Path $PSScriptRoot "..\modules\dots-data.lua"
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $out)).Path + "\dots-data.lua", $sb.ToString().Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("dots-data.lua: " + $raid.Count + " raid debuffs, " + $seen.Count + " spell ids")
